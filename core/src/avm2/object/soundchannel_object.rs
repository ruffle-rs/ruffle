use std::cell::{Cell, RefCell};

/// A class instance allocator that allocates SoundChannel objects.
pub fn sound_channel_allocator<'gc>(
    class: ClassObject<'gc>,
    activation: &mut Activation<'_, 'gc>,
) -> Result<Object<'gc>, Error<'gc>> {
    let base = ScriptObjectData::new(class);

    Ok(SoundChannelObject(Gc::new(
        activation.gc(),
        SoundChannelObjectData {
            base,
            sound_channel_data: RefCell::new(SoundChannelData::NotLoaded {
                sound_transform: None,
                should_stop: false,
            }),
            position: Cell::new(0.0),
            generator: None,
        },
    ))
    .into())
}

#[derive(Clone, Collect, Copy)]
#[collect(no_drop)]
pub struct SoundChannelObject<'gc>(pub Gc<'gc, SoundChannelObjectData<'gc>>);

#[derive(Clone, Collect, Copy, Debug)]
#[collect(no_drop)]
pub struct SoundChannelObjectWeak<'gc>(pub GcWeak<'gc, SoundChannelObjectData<'gc>>);

impl fmt::Debug for SoundChannelObject<'_> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("SoundChannelObject")
            .field("ptr", &Gc::as_ptr(self.0))
            .finish()
    }
}

#[derive(Collect, HasPrefixField)]
#[collect(no_drop)]
#[repr(C, align(8))]
pub struct SoundChannelObjectData<'gc> {
    /// Base script object
    base: ScriptObjectData<'gc>,

    /// The sound this object holds.
    sound_channel_data: RefCell<SoundChannelData>,

    /// Position of the last playing sound in milliseconds.
    position: Cell<f64>,

    /// The generator of the samples this channel plays, if it plays a `Sound`
    /// with no data.
    generator: Option<Gc<'gc, SampleGenerator<'gc>>>,
}

/// Generates the samples of a channel playing a `Sound` with no data, which
/// asks its `sampleData` listeners for samples while it plays.
#[derive(Collect)]
#[collect(no_drop)]
struct SampleGenerator<'gc> {
    /// The `Sound` whose listeners generate the samples.
    sound: SoundObject<'gc>,

    /// The `ByteArray` the listeners write samples into.
    data: ByteArrayObject<'gc>,

    #[collect(require_static)]
    queue: SampleQueue,

    /// The number of sample frames generated so far.
    generated: Cell<u32>,
}

pub enum SoundChannelData {
    NotLoaded {
        sound_transform: Option<SoundTransform>,
        should_stop: bool,
    },
    Loaded {
        sound_instance: SoundInstanceHandle,
    },
}

impl<'gc> SoundChannelObject<'gc> {
    /// The least samples a `sampleData` listener can write without ending the sound.
    const MIN_GENERATED_SAMPLES: u32 = 2048;

    /// The most samples a `sampleData` listener can write.
    const MAX_GENERATED_SAMPLES: u32 = 8192;

    /// Create an empty SoundChannel instance.
    pub fn empty(activation: &mut Activation<'_, 'gc>) -> Self {
        Self::new(activation, None)
    }

    /// Create a SoundChannel instance that plays samples generated by the
    /// `sampleData` listeners of `sound`.
    pub fn generated(activation: &mut Activation<'_, 'gc>, sound: SoundObject<'gc>) -> Self {
        let data = sound.sample_data(activation.context);
        let generator = Gc::new(
            activation.gc(),
            SampleGenerator {
                sound,
                data,
                queue: SampleQueue::default(),
                generated: Cell::new(0),
            },
        );
        Self::new(activation, Some(generator))
    }

    fn new(
        activation: &mut Activation<'_, 'gc>,
        generator: Option<Gc<'gc, SampleGenerator<'gc>>>,
    ) -> Self {
        let class = activation.avm2().classes().soundchannel;
        let base = ScriptObjectData::new(class);

        SoundChannelObject(Gc::new(
            activation.gc(),
            SoundChannelObjectData {
                base,
                sound_channel_data: RefCell::new(SoundChannelData::NotLoaded {
                    sound_transform: None,
                    should_stop: false,
                }),
                position: Cell::new(0.0),
                generator,
            },
        ))
    }

    /// Starts playing the samples of a generated channel.
    ///
    /// Like Flash, this asks for the first samples right away, and keeps
    /// asking for as long as the listeners write the most samples they can,
    /// up to five such blocks.
    ///
    /// Returns `false` if the sound could not be started.
    pub fn start_generator(
        self,
        context: &mut UpdateContext<'gc>,
        sound_transform: Option<SoundTransform>,
    ) -> bool {
        let Some(generator) = self.0.generator else {
            return false;
        };
        let Some(instance) = context.audio_manager.start_sample_queue(
            context.audio,
            generator.queue.clone(),
            sound_transform,
        ) else {
            return false;
        };
        self.set_sound_instance(context, instance);
        context.attach_avm2_sound_channel(instance, self);

        while let Some(Self::MAX_GENERATED_SAMPLES) = self.request_samples(context)
            && generator.generated.get() < 5 * Self::MAX_GENERATED_SAMPLES
        {}
        true
    }

    /// Asks for samples until `lead` sample frames are queued ahead of
    /// playback, if this channel plays generated samples.
    pub fn generate_samples(self, context: &mut UpdateContext<'gc>, lead: u32) {
        let (Some(generator), Some(instance)) = (self.0.generator, self.instance()) else {
            return;
        };
        let Some(position) = context.audio.get_sound_position(instance) else {
            return;
        };
        // Measured once: playback may advance while the listeners run, and
        // chasing it would never end if they generate slower than real time.
        let played = (position * f64::from(SampleQueue::SAMPLE_RATE) / 1000.0).round() as u32;
        let target = played.saturating_add(lead);
        while generator.generated.get() < target && self.request_samples(context).is_some() {}
    }

    /// Dispatches a `sampleData` event to ask for more samples, and queues
    /// those that the listeners write.
    ///
    /// Returns the number of sample frames queued, or `None` if the sound has
    /// ended or been stopped.
    fn request_samples(self, context: &mut UpdateContext<'gc>) -> Option<u32> {
        let generator = self.0.generator?;
        let instance = self.instance()?;
        if generator.queue.is_ended() || !context.audio_manager.is_sound_playing(instance) {
            return None;
        }

        generator.data.storage().set_position(0);
        let mut activation = Activation::from_nothing(context);
        let event = EventObject::sample_data_event(
            &mut activation,
            generator.generated.get().into(),
            generator.data.into(),
        );
        Avm2::dispatch_event(context, event, generator.sound.into());
        if !context.audio_manager.is_sound_playing(instance) {
            // A listener stopped the sound.
            return None;
        }

        // Flash counts the samples up to the position, not the length.
        let data = generator.data.storage();
        let num_samples = (data.position().min(data.len()) / 8) as u32;
        if num_samples > Self::MAX_GENERATED_SAMPLES {
            // Flash plays none of them, and ends the sound.
            generator.queue.end();
            return None;
        }
        generator.queue.push((0..num_samples as usize).map(|i| {
            // Saturating, NaN becomes 0.
            let sample = |offset| (data.read_float_at(offset).unwrap_or(0.0) * 32768.0) as i16;
            [sample(i * 8), sample(i * 8 + 4)]
        }));
        generator
            .generated
            .set(generator.generated.get().saturating_add(num_samples));

        if num_samples < Self::MIN_GENERATED_SAMPLES {
            // Fewer samples end the sound once they have played.
            generator.queue.end();
            return None;
        }
        Some(num_samples)
    }

    /// Return the position of the playing sound in seconds.
    pub fn position(self, context: &mut UpdateContext<'gc>) -> f64 {
        // The position is cached on read. This means that if the position isn't read until after
        // the sound has played, the position will be 0 (#9952).
        let sound_channel_data = self.0.sound_channel_data.borrow();
        if let SoundChannelData::Loaded { sound_instance } = &*sound_channel_data
            && let Some(pos) = context.audio.get_sound_position(*sound_instance)
        {
            self.0.position.set(pos);
        }

        self.0.position.get()
    }

    /// Called when the sound of this channel has played out, before
    /// `soundComplete` is dispatched.
    pub fn sound_completed(self) {
        if let Some(generator) = self.0.generator {
            // A generated sound ends where its samples end.
            let generated = f64::from(generator.generated.get());
            self.0
                .position
                .set(generated * 1000.0 / f64::from(SampleQueue::SAMPLE_RATE));
        }
    }

    pub fn instance(self) -> Option<SoundInstanceHandle> {
        let sound_channel_data = self.0.sound_channel_data.borrow();
        match &*sound_channel_data {
            SoundChannelData::NotLoaded { .. } => None,
            SoundChannelData::Loaded { sound_instance } => Some(*sound_instance),
        }
    }

    pub fn set_sound_instance(
        self,
        context: &mut UpdateContext<'gc>,
        instance: SoundInstanceHandle,
    ) {
        let mut sound_channel_data = self.0.sound_channel_data.borrow_mut();
        match &mut *sound_channel_data {
            SoundChannelData::NotLoaded {
                sound_transform,
                should_stop,
            } => {
                if let Some(sound_transform) = sound_transform {
                    context.set_local_sound_transform(instance, *sound_transform);
                }

                if *should_stop {
                    context.stop_sound(instance);
                }
                *sound_channel_data = SoundChannelData::Loaded {
                    sound_instance: instance,
                }
            }
            SoundChannelData::Loaded { sound_instance } => {
                panic!(
                    "Tried to replace loaded sound instance {sound_instance:?} with {instance:?}"
                )
            }
        }
    }

    pub fn sound_transform(self, activation: &mut Activation<'_, 'gc>) -> Option<SoundTransform> {
        let sound_channel_data = self.0.sound_channel_data.borrow();
        match *sound_channel_data {
            SoundChannelData::NotLoaded {
                sound_transform, ..
            } => sound_transform,
            SoundChannelData::Loaded { sound_instance } => activation
                .context
                .local_sound_transform(sound_instance)
                .cloned(),
        }
    }

    pub fn set_sound_transform(
        self,
        activation: &mut Activation<'_, 'gc>,
        new_sound_transform: SoundTransform,
    ) {
        let mut sound_channel_data = self.0.sound_channel_data.borrow_mut();
        match &mut *sound_channel_data {
            SoundChannelData::NotLoaded {
                sound_transform, ..
            } => {
                *sound_transform = Some(new_sound_transform);
            }
            SoundChannelData::Loaded { sound_instance } => {
                activation
                    .context
                    .set_local_sound_transform(*sound_instance, new_sound_transform);
            }
        }
    }

    pub fn stop(self, activation: &mut Activation<'_, 'gc>) {
        let mut sound_channel_data = self.0.sound_channel_data.borrow_mut();
        match &mut *sound_channel_data {
            SoundChannelData::NotLoaded {
                sound_transform: _,
                should_stop,
            } => {
                *should_stop = true;
            }
            SoundChannelData::Loaded { sound_instance } => {
                activation.context.stop_sound(*sound_instance);
            }
        }
    }
}

impl<'gc> TObject<'gc> for SoundChannelObject<'gc> {
    fn gc_base(&self) -> Gc<'gc, ScriptObjectData<'gc>> {
        HasPrefixField::as_prefix_gc(self.0)
    }
}
